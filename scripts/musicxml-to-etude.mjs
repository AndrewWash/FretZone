#!/usr/bin/env node
// Dev-time MusicXML → Sor catalog entry converter.
//
// Usage:
//   npm run import-etude -- path/to/file.musicxml [--id sor-op60-no1] [--title "Op. 60 No. 1"]
//
// Emits a TypeScript snippet to stdout that can be pasted into
// src/app/core/sor/catalog.ts. Notes that lack <string>/<fret> data fall
// through with `stringId`/`fret` omitted and a // TODO comment — fill those
// in by hand before publishing the etude.

import { readFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { XMLParser } from 'fast-xml-parser';

const argv = process.argv.slice(2);
if (!argv.length) {
  console.error('Usage: import-etude <file.musicxml> [--id <slug>] [--title <title>]');
  process.exit(1);
}
const inputPath = resolve(argv[0]);
if (!existsSync(inputPath)) {
  console.error(`File not found: ${inputPath}`);
  process.exit(1);
}
function flag(name, def) {
  const i = argv.indexOf(name);
  return i >= 0 && argv[i + 1] ? argv[i + 1] : def;
}
const etudeId = flag('--id', 'sor-op60-no1');
const etudeTitle = flag('--title', 'Op. 60 No. 1');

const xml = readFileSync(inputPath, 'utf8');
const parser = new XMLParser({
  ignoreAttributes: false,
  attributeNamePrefix: '@_',
  allowBooleanAttributes: true,
  parseTagValue: true,
  trimValues: true,
});
const tree = parser.parse(xml);
const root = tree['score-partwise'] || tree['score-timewise'];
if (!root) {
  console.error('Not a MusicXML score (missing score-partwise/score-timewise).');
  process.exit(1);
}

const parts = arr(root.part);
if (!parts.length) {
  console.error('No <part> in score.');
  process.exit(1);
}

// Walk only the first part (classical guitar etudes are single-part).
const measures = arr(parts[0].measure);

// Pitch step → semitone offset from C.
const STEP_PC = { C:0, D:2, E:4, F:5, G:7, A:9, B:11 };

// MusicXML <type> → our duration code.
const TYPE_TO_DUR = {
  whole: 'w', half: 'h', quarter: 'q',
  eighth: '8', '16th': '16', '32nd': '32',
};

const collected = [];   // { barIdx, voice: 'upper'|'lower', note }
let firstAttrs = null;

measures.forEach((m, barIdx) => {
  if (!firstAttrs && m.attributes) firstAttrs = m.attributes;
  const elements = arr(m.note);
  for (const n of elements) {
    const isRest = 'rest' in n;
    const voiceRaw = String(n.voice ?? '1');
    const voice = voiceRaw === '1' ? 'upper' : 'lower';

    const type = String(n.type ?? 'quarter');
    const duration = TYPE_TO_DUR[type] || 'q';
    const dotted = 'dot' in n;

    let midi;
    let stringId, fret;
    let lhFinger;
    let rhFinger;
    let tieToNext = false;

    if (!isRest && n.pitch) {
      const step = String(n.pitch.step ?? 'C');
      const octave = Number(n.pitch.octave ?? 4);
      const alter = Number(n.pitch.alter ?? 0);
      midi = (octave + 1) * 12 + STEP_PC[step] + alter;
    }

    if (n.notations) {
      const ties = arr(n.notations.tied);
      if (ties.some(t => String(t['@_type']) === 'start')) tieToNext = true;
      const tech = n.notations.technical;
      if (tech) {
        if (tech['string'] != null) stringId = Number(tech.string);
        if (tech['fret'] != null) fret = Number(tech.fret);
        if (tech['fingering'] != null) {
          // LH fingerings render as 1..4 (sometimes 0 for open). Some files
          // use <fingering> for RH (p/i/m/a as letters); detect by content.
          const fn = arr(tech.fingering)[0];
          const txt = (typeof fn === 'object' ? fn['#text'] : fn) ?? '';
          const s = String(txt).trim().toLowerCase();
          if (/^[0-4]$/.test(s)) lhFinger = Number(s);
          else if (/^[pima]$/.test(s)) rhFinger = s;
        }
      }
    }

    collected.push({
      barIdx,
      voice,
      isRest,
      duration,
      dotted,
      midi,
      stringId,
      fret,
      lhFinger,
      rhFinger,
      tieToNext,
    });
  }
});

// Time signature from the first <attributes><time>.
let timeSig = '2/4';
if (firstAttrs?.time) {
  const beats = Number(firstAttrs.time.beats ?? 2);
  const beatType = Number(firstAttrs.time['beat-type'] ?? 4);
  timeSig = `${beats}/${beatType}`;
}

// Bucket notes into bars + voices.
const totalBars = measures.length;
const bars = Array.from({ length: totalBars }, () => ({ upper: [], lower: [] }));
for (const c of collected) {
  bars[c.barIdx][c.voice].push(c);
}

// Emit TS.
const lines = [];
lines.push(`// Generated by scripts/musicxml-to-etude.mjs from ${argv[0]}`);
lines.push(`// Review TODO markers (missing string/fret) before publishing.`);
lines.push(``);
lines.push(`import type { EtudeBar, SorEtude } from './models';`);
lines.push(``);
lines.push(`const ${idToConst(etudeId)}_BARS: EtudeBar[] = [`);
for (let bi = 0; bi < bars.length; bi++) {
  const bar = bars[bi];
  lines.push(`  // Bar ${bi + 1}`);
  lines.push(`  {`);
  for (const voice of ['upper', 'lower']) {
    const arr = bar[voice];
    if (!arr.length) {
      lines.push(`    ${voice}: [],`);
      continue;
    }
    lines.push(`    ${voice}: [`);
    for (const n of arr) {
      lines.push(`      ${emitNote(n)},`);
    }
    lines.push(`    ],`);
  }
  lines.push(`  },`);
}
lines.push(`];`);
lines.push(``);
lines.push(`export const ${idToConst(etudeId)}: SorEtude = {`);
lines.push(`  id: '${etudeId}',`);
lines.push(`  opus: 60,`);
lines.push(`  number: 1,`);
lines.push(`  title: '${etudeTitle.replace(/'/g, "\\'")}',`);
lines.push(`  key: 'C',`);
lines.push(`  keyMode: 'Ionian',`);
lines.push(`  timeSignature: '${timeSig}',`);
lines.push(`  defaultBpm: 72,`);
lines.push(`  bars: ${idToConst(etudeId)}_BARS,`);
lines.push(`  enabled: true,`);
lines.push(`};`);
lines.push(``);

process.stdout.write(lines.join('\n'));

function arr(x) {
  if (x == null) return [];
  return Array.isArray(x) ? x : [x];
}

function idToConst(id) {
  return id.toUpperCase().replace(/[-.]/g, '_');
}

function emitNote(n) {
  if (n.isRest) {
    return `{ kind: 'rest', duration: '${n.duration}'${n.dotted ? ', dotted: true' : ''} }`;
  }
  const parts = [`kind: 'note'`, `duration: '${n.duration}'`];
  if (n.dotted) parts.push(`dotted: true`);
  if (n.midi != null) parts.push(`midi: ${n.midi}`);
  if (n.stringId != null) parts.push(`stringId: ${n.stringId}`);
  if (n.fret != null) parts.push(`fret: ${n.fret}`);
  if (n.lhFinger != null) parts.push(`lhFinger: ${n.lhFinger}`);
  if (n.rhFinger != null) parts.push(`rhFinger: '${n.rhFinger}'`);
  if (n.tieToNext) parts.push(`tieToNext: true`);
  const missing = (n.stringId == null || n.fret == null);
  return `{ ${parts.join(', ')} }${missing ? ' // TODO: fill stringId/fret' : ''}`;
}
